#!/usr/bin/env python3
"""Derive the plugin wire schema from this checkout's generated Telegram API.

No separately versioned Android/Telethon schema is used: IDs, order, flag bits
and return types come from the same serializers used by the native client.
"""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent

def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()

def optional_flags(body, prefix):
    result = {}
    pattern = r'if Int\(' + re.escape(prefix) + r'(flags\d*)\) & Int\(1 << (\d+)\) != 0 \{(.*?)\n\s*\}'
    for match in re.finditer(pattern, body, re.S):
        fields = re.findall(re.escape(prefix) + r'(\w+)', match[3]) if prefix else re.findall(r'\b(\w+)!', match[3])
        for name in fields: result[name] = [match[1], int(match[2])]
    return result

def fields_from_pairs(pairs, body, prefix):
    flags = optional_flags(body, prefix)
    result = []
    for name, kind in pairs:
        optional = kind.endswith('?');kind = kind.rstrip('?')
        if kind == 'Buffer':
            if re.search(r'serializeInt256\(' + re.escape(prefix + name), body): kind = 'int256'
            elif re.search(r'serializeInt128\(' + re.escape(prefix + name), body): kind = 'int128'
        field = {'name': snake(name), 'swift': name, 'type': kind}
        if name in flags: field['flag'] = flags[name]
        elif optional: raise ValueError('Unresolved optional field: ' + name)
        result.append(field)
    return result

def generate():
    models = []
    for path in sorted((ROOT / 'submodules/TelegramApi/Sources').glob('Api[0-9]*.swift')):
        text = path.read_text().replace('`', '')
        sections = list(re.finditer(r'public extension (Api[\w.]*) \{', text))
        for i, section in enumerate(sections):
            content = text[section.end():sections[i + 1].start() if i + 1 < len(sections) else len(text)]
            namespace = section[1].removeprefix('Api').strip('.')
            if namespace.startswith('functions.'):
                header = re.search(r'static func (\w+)\((.*?)\) -> \(FunctionDescription, Buffer, DeserializeFunctionResponse<(.*?)>\)', content)
                if not header: continue
                wire = re.search(r'buffer.appendInt32\((-?\d+)\)', content)
                body = content[:content.index('return (FunctionDescription')]
                pairs = re.findall(r'(\w+): ([\w.\[\]?]+)(?:, |$)', header[2])
                if len(pairs) != (0 if not header[2] else header[2].count(':')): raise ValueError('Unsupported function declaration')
                name = namespace.removeprefix('functions.') + '.' + header[1]
                models.append({'name': name, 'id': int(wire[1]), 'fields': fields_from_pairs(pairs, body, ''), 'result': header[3], 'function': True})
            else:
                enum = re.search(r'(?:indirect )?enum (\w+): TypeConstructorDescription', content)
                if not enum: continue
                properties = {}
                for cls in re.finditer(r'public class Cons_(\w+): TypeConstructorDescription \{(.*?)(?:public init|public func)', content, re.S):
                    properties[cls[1]] = re.findall(r'public var (\w+): ([\w.\[\]?]+)', cls[2])
                serializer = re.search(r'public func serialize\(.*?\n(.*?)\n\s*public func descriptionFields', content, re.S)
                if not serializer: raise ValueError('Missing serializer: ' + enum[1])
                for case in re.finditer(r'case \.(\w+)(?:\(let _data\))?:\n(.*?)\n\s*break', serializer[1], re.S):
                    wire = re.search(r'buffer.appendInt32\((-?\d+)\)', case[2])
                    if not wire: raise ValueError('Missing constructor ID: ' + case[1])
                    name = (namespace + '.' if namespace else '') + case[1]
                    base = (namespace + '.' if namespace else '') + enum[1]
                    models.append({'name': name, 'base': base, 'id': int(wire[1]), 'fields': fields_from_pairs(properties.get(case[1], []), case[2], '_data.')})
    ids = [m['id'] for m in models]
    if len(ids) != len(set(ids)): raise ValueError('Duplicate constructor IDs')
    if len(models) < 2000: raise ValueError('Incomplete Telegram API schema')
    boolean_metadata = json.loads((ROOT / 'scripts/plugin-tl-flags.json').read_text())['constructors']
    for model in models:
        entry = boolean_metadata.get(str(model['id'] & 0xffffffff))
        if entry and entry['name'] == model['name']: model['booleans'] = entry['fields']
    target = ROOT / 'submodules/AfterGramPython/SDK/aftergram_tl_schema.json'
    target.write_text(json.dumps(models, ensure_ascii=False, separators=(',', ':')) + '\n')
    native = ROOT / 'submodules/TelegramCore/Sources/Settings/AfterGramApiFunctions.swift'
    native.write_text('// Generated by scripts/generate-plugin-tl.py.\nlet afterGramApiFunctionNames: [Int32: String] = [\n' + ''.join('    ' + str(m['id']) + ': ' + json.dumps(m['name']) + ',\n' for m in models if m.get('function')) + ']\nlet afterGramApiFunctionResultTypes: [String: String] = [\n' + ''.join('    ' + json.dumps(m['name']) + ': ' + json.dumps(m['result']) + ',\n' for m in models if m.get('function')) + ']\n')
    print('Generated', sum(bool(m.get('function')) for m in models), 'requests and', sum(not m.get('function') for m in models), 'constructors.')

if __name__ == '__main__': generate()
